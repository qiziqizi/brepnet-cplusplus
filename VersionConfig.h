// ============================================================================
// BRepNet C++ 版本控制
// ============================================================================
// 切换版本时改这一个数字：
//   123 = brepnet_123 + uvs_local (组合2)
//   4   = brepnet_4 + uvs_4       (组合1)
//
// 修改后重新编译即可切换版本，无需改其他文件。
// ============================================================================

#define BREPNET_VERSION 123

// 编译期检查：只允许 123 或 4
#if BREPNET_VERSION != 123 && BREPNET_VERSION != 4
#error "BREPNET_VERSION must be 123 or 4"
#endif